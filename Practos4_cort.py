# 1. Кортеж из пяти чисел: первый, последний и средний элементы
t1 = (10, 20, 30, 40, 50)
print("Первый:", t1[0])
print("Последний:", t1[-1])
print("Средний:", t1[len(t1) // 2])

# 2. Из кортежа из восьми чисел: первые два, последние два, обратный порядок
t2 = (1, 2, 3, 4, 5, 6, 7, 8)
print("Первые два:", t2[:2])
print("Последние два:", t2[-2:])
print("В обратном порядке:", t2[::-1])

# 3. Длина, сумма, минимум, максимум кортежа
t3 = (5, 2, 8, 1, 9, 3)
print("Длина:", len(t3))
print("Сумма:", sum(t3))
print("Минимум:", min(t3))
print("Максимум:", max(t3))
# 4. Есть ли x в кортеже, сколько раз, индекс первого вхождения
t4 = (1, 2, 3, 2, 4, 2, 5)
x = 2
print(f"Число {x} в кортеже:", x in t4)
print(f"Встречается {t4.count(x)} раз(а)")
print("Индекс первого вхождения:", t4.index(x))

# 5. Объединение двух кортежей
t5a = (1, 2, 3)
t5b = (4, 5, 6)
print("Объединённый кортеж:", t5a + t5b)

# 6. Кортеж из одного элемента и его тип
t6 = (42,)
print("Кортеж:", t6)
print("Тип:", type(t6))

# 7. Распаковка кортежа (имя, возраст, город)
person = ("Иван", 25, "Москва")
name, age, city = person
print("Имя:", name)
print("Возраст:", age)
print("Город:", city)

# 8. Обмен значений двух переменных с помощью кортежа
a, b = 5, 10
print("До обмена: a =", a, ", b =", b)
a, b = b, a
print("После обмена: a =", a, ", b =", b)

# 9. Замена второго элемента кортежа
t9 = (1, 2, 3, 4)
new_t9 = t9[:1] + (99,) + t9[2:]
print("Новый кортеж:", new_t9)

# 10. Кортеж без повторов, отсортированный по возрастанию
t10 = (3, 1, 2, 3, 1, 4, 2, 5)
result = tuple(sorted(set(t10)))
print("Без повторов, отсортированный:", result)