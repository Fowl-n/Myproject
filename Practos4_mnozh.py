# 1. Создайте множество из списка с повторяющимися числами
n = [1, 2, 2, 3, 3, 3, 4, 4, 4, 4]
m = set(n)
print("Множество:", m)
print("Количество элементов:", len(m))

# 2. Создайте множество из трёх чисел. Добавьте новый, удалите один
s = {10, 20, 30}
print("Исходное множество:", s)
s.add(40)
print("После добавления 40:", s)
s.remove(20)
print("После удаления 20:", s)

# 3. Объединение двух множеств
a = {1, 2, 3, 4}
b = {3, 4, 5, 6}
print("Объединение:", a | b)

# 4. Пересечение двух множеств
print("Пересечение:", a & b)

# 5. Элементы первого, которых нет во втором, и наоборот
print("В первом, но не во втором:", a - b)
print("Во втором, но не в первом:", b - a)

# 6. Элементы, которые входят ровно в одно из множеств
print("Симметрическая разность:", a ^ b)

# 7. Есть ли число x в множестве
x = 3
print(f"Число {x} в множестве a:", x in a)

# 8. Является ли первое множество подмножеством второго
c = {1, 2}
print("c является подмножеством a:", c.issubset(a))

# 9. Множество различных символов строки
text = "hello world"
chars = set(text)
print("Различные символы:", chars)
print("Количество:", len(chars))

# 10. Отсортированный список общих элементов двух списков без повторов
list1 = [1, 2, 2, 3, 4, 5]
list2 = [3, 4, 4, 5, 6, 7]
common = sorted(set(list1) & set(list2))
print("Общие элементы без повторов:", common)