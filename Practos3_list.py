# 6. Дан список и число x. Выведите, есть ли x в списке, сколько раз оно встречается и индекс первого вхождения.
lst = [1, 2, 3, 2, 4, 2, 5]
x = 2
if x in lst:
    print(f"Число {x} есть в списке")
    print("Количество вхождений:", lst.count(x))
    print("Индекс первого вхождения:", lst.index(x))
else:
    print(f"Числа {x} нет в списке")

