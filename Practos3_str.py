print("Первый символ:", s[0])
print("Последний символ:", s[-1])

# 2. Выведите символ, стоящий в середине строки. Для строки чётной длины выведите оба средних.
s = input("Введите строку: ")
n = len(s)
mid = n // 2
if n % 2 == 0:
    print("Средние символы:", s[mid - 1], s[mid])
else:
    print("Средний символ:", s[mid])

# 3. Из строки получите: первые три символа, последние три, все символы с чётными индексами, строку в обратном порядке.
s = input("Введите строку: ")
print("Первые три:", s[:3])
print("Последние три:", s[-3:])
print("Чётные индексы:", s[::2])
print("Обратный порядок:", s[::-1])

# 4. Дана строка. Выведите её в верхнем регистре, в нижнем регистре и с заглавной
s = input("Введите строку: ")
