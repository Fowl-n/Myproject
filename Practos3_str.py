# 7. Дана строка с лишними пробелами в начале и в конце. Удалите их и выведите длину результата.
s = input("Введите строку с пробелами: ")
stripped = s.strip()
print(f"Результат: {stripped}")
print("Длина:", len(stripped))

# 8. Дана строка из имени и фамилии через пробел. Выведите сначала фамилию, потом имя, а затем инициалы.
s = input("Введите имя и фамилию: ")
parts = s.split()
name, surname = parts[0], parts[1]
print("Фамилия:", surname)
print("Имя:", name)
print("Инициалы:", name[0].upper() + "." + surname[0].upper() + ".")

