# 5. Дана строка и символ c. Выведите, есть ли c в строке, сколько раз он встречается и индекс первого вхождения.
s = input("Введите строку: ")
c = input("Введите символ: ")
if c in s:
    print(f"Символ '{c}' есть в строке")
    print("Количество вхождений:", s.count(c))
    print("Индекс первого вхождения:", s.find(c))
else:
    print(f"Символа '{c}' нет в строке")

